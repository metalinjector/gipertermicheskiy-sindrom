# -*- coding: utf-8 -*-
import sys; sys.path.insert(0, __import__('os').path.dirname(__import__('os').path.abspath(__file__)))
from svglib import *

c = Canvas(1600, 900)
c.title("Спектр тепловых поражений: где место «теплового повреждения»",
        "по консенсусу ACSM 2023 и руководству WMS; граница тяжести — состояние ЦНС и органов, а не цифра на термометре")

# gradient bar
c.parts.append('<defs><linearGradient id="g" x1="0" x2="1"><stop offset="0" stop-color="#bbf7d0"/><stop offset="0.5" stop-color="#fde68a"/><stop offset="1" stop-color="#fca5a5"/></linearGradient></defs>')
c.parts.append('<rect x="40" y="110" width="1520" height="34" rx="17" fill="url(#g)"/>')
c.text(60, 134, "лёгкие", 16, INK, "start", True)
c.text(1540, 134, "жизнеугрожающие", 16, INK, "end", True)

cards = [
    ("Тепловые мышечные судороги", "(exercise-associated muscle cramps)", GRN_F, GRN_S,
     ["T_core обычно нормальная или умеренно повышена", "Болезненные спазмы работающих мышц", "Покой, растяжение, регидратация с солью", "ЦНС сохранна"]),
    ("Тепловой обморок", "(heat syncope)", GRN_F, GRN_S,
     ["T_core обычно < 38 °C", "Ортостаз + вазодилатация; сознание восстанавливается лёжа сразу", "Исключить аритмию, гипогликемию", "ЦНС сохранна после эпизода"]),
    ("Тепловое истощение", "(heat exhaustion)", AMB_F, AMB_S,
     ["T_core ориентировочно 38,5–40 °C", "Слабость, тошнота, головная боль, тахикардия, профузный пот", "Отдых в прохладе, охлаждение, регидратация", "ЦНС сохранна: нет делирия, судорог, комы"]),
    ("Тепловое повреждение", "(exertional heat injury)", AMB_F, AMB_S,
     ["Гипертермия + ОБЪЕКТИВНОЕ повреждение органов: рабдомиолиз (КФК), ОПП (креатинин), цитолиз (АЛТ/АСТ)", "БЕЗ выраженной дисфункции ЦНС", "Лаборатория обязательна, наблюдение в стационаре", "Не «лёгкий» пациент"]),
    ("Тепловой удар", "(heat stroke)", RED_F, RED_S,
     ["T_core > 40 °C (после начала охлаждения может быть ниже)", "ДИСФУНКЦИЯ ЦНС: спутанность, делирий, атаксия, судороги, кома", "Погружение в холодную воду немедленно: cool first, transport second", "Летальность определяется временем выше порога"]),
]
cw, gap, y0, ch = 290, 17, 170, 330
for i, (t, lat, f, s, items) in enumerate(cards):
    x = 40 + i * (cw + gap)
    c.rect(x, y0, cw, ch, f, s, 3, 14)
    yy = c.lines(x + 14, y0 + 32, wrap(t, cw - 28, 19, True), 19, s, "start", True)
    yy = c.lines(x + 14, yy + 2, wrap(lat, cw - 28, 13), 13, MUTED, "start", False, 1.25, True) + 8
    for it in items:
        yy = c.lines(x + 14, yy, wrap("• " + it, cw - 28, 15), 15, INK) + 7
    c.line(x + cw / 2, 144, x + cw / 2, y0 - 4, s, 2.5, arrow=True)

# CNS bracket
c.line(40, 525, 1250, 525, GRN_S, 4)
c.text(645, 550, "функция ЦНС сохранна", 16, GRN_S, "middle", True)
c.line(1270, 525, 1560, 525, RED_S, 4)
c.text(1415, 550, "дисфункция ЦНС", 16, RED_S, "middle", True)

c.box(40, 580, 745, 230, "Три оговорки, отличающие схему от реальности",
      ["• Стадии не обязаны идти последовательно: тепловой удар при нагрузке развивается и без предшествующего «истощения»",
       "• Потоотделение не разделяет формы: профузный пот типичен для EHS, ангидроз — для классического теплового удара, но возможны обе картины",
       "• Температура, измеренная после начала охлаждения или не ректально, не снимает диагноз"],
      fill=GRY_F, stroke=GRY_S, tsize=18, bsize=15)
c.box(815, 580, 745, 230, "Зачем нужна категория «тепловое повреждение»",
      ["• У пациента без делирия легко пропустить рабдомиолиз и ОПП: нужна КФК, креатинин, калий, АЛТ/АСТ, анализ мочи",
       "• Возвращение к нагрузкам — только после нормализации лабораторных показателей и поэтапно (ACSM 2023)",
       "• Повторные эпизоды или семейный анамнез — повод обсудить обследование на предрасположенность к MH (§ 13.1)"],
      fill=BLU_F, stroke=BLU_S, tsize=18, bsize=15)
c.footer("Схема аудита 2026-10 к § 4.3.4. Границы температуры ориентировочные; разделяющий признак — ЦНС (тепловой удар) и объективное повреждение органов (тепловое повреждение).")
c.save(sys.argv[1])
