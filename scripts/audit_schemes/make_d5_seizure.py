# -*- coding: utf-8 -*-
import sys; sys.path.insert(0, __import__('os').path.dirname(__import__('os').path.abspath(__file__)))
from svglib import *

c = Canvas(1600, 900)
c.title("Судороги на фоне гипертермии: лестница терапии и дозы",
        "AES 2016 / ESETT 2019 / RAMPART 2012; охлаждение и поиск причины продолжаются параллельно на каждой ступени")
c.rect(40, 96, 1520, 40, RED_F, RED_S, 2, 10)
c.text(800, 123, "Каждая следующая ступень — только если приступ ПРОДОЛЖАЕТСЯ или повторяется без восстановления сознания", 19, RED_S, "middle", True)

steps = [
    ("0–5 мин: стабилизация", GRY_F, GRY_S,
     ["• ABC, боковое положение, O₂, SpO₂, ЭКГ", "• Глюкоза крови; тиамин при подозрении на дефицит",
      "• T_core ректально; охлаждение НЕ прерывать — судороги сами греют",
      "• Поиск причины: нейроинфекция, гипонатриемия, токсидром, отёк мозга, гипогликемия"]),
    ("5 мин: 1-я линия — бензодиазепин", GRN_F, GRN_S,
     ["• Лоразепам в/в 0,1 мг/кг (макс 4 мг)", "• Диазепам в/в 0,15–0,2 мг/кг (макс 10 мг); у детей 0,1–0,2 мг/кг",
      "• Нет вены: мидазолам в/м 10 мг (> 40 кг) / 5 мг (13–40 кг), у детей 0,1–0,2 мг/кг; буккально 0,3–0,5 мг/кг; интраназально 0,2 мг/кг; диазепам ректально 0,5 мг/кг (макс 20 мг)",
      "• Повтор однократно через 5–10 мин"]),
    ("20 мин: 2-я линия", AMB_F, AMB_S,
     ["AES/ESETT (равная эффективность ≈ 45–47 %):", "• леветирацетам 60 мг/кг (макс 4500 мг)", "• вальпроат 40 мг/кг (макс 3000 мг)",
      "• фосфенитоин 20 мг ФЭ/кг (макс 1500 мг)",
      "Отечественные инструкции — ниже: вальпроат 15–30, леветирацетам 20–60, фенитоин 15–20 мг/кг (≤ 50 мг/мин, под ЭКГ и АД)"]),
    ("40 мин: рефрактерный статус", RED_F, RED_S,
     ["• Общая анестезия: мидазолам, пропофол или тиопентал в/в", "• Интубация, ИВЛ, ЭЭГ-мониторинг", "• ОРИТ; продолжать лечение причины и охлаждение"]),
]
bw, bh, gap, y0 = 355, 330, 33, 160
for i, (t, f, s, items) in enumerate(steps):
    x = 40 + i * (bw + gap)
    c.rect(x, y0, bw, bh, f, s, 3, 14)
    yy = c.lines(x + 14, y0 + 34, wrap(t, bw - 28, 20, True), 20, s, "start", True) + 6
    for it in items:
        yy = c.lines(x + 14, yy, wrap(it, bw - 28, 15.5), 15.5, INK) + 7
    if i < 3:
        c.line(x + bw + 4, y0 + bh / 2, x + bw + gap - 4, y0 + bh / 2, MUTED, 3, arrow=True)

c.box(40, 525, 745, 230, "Что НЕ является показанием к бензодиазепину",
      ["• «судорожная готовность», тремор, озноб и дрожь при охлаждении (дрожь лечат иначе — § 9.2.3)",
       "• уже закончившийся простой фебрильный приступ у ребёнка с восстановленным сознанием — нужны наблюдение и поиск причины (§ 12.1.2)",
       "• высокая температура сама по себе"],
      fill=BLU_F, stroke=BLU_S, tsize=19, bsize=16)
c.box(815, 525, 745, 230, "Пути введения у детей",
      ["• В/в диазепам 0,1–0,2 мг/кг, макс 10 мг на введение; дозы 0,3–0,5 мг/кг в/в избыточны — угнетение дыхания",
       "• В/м диазепам НЕ рекомендуется (медленная, непредсказуемая абсорбция)",
       "• Без вены: мидазолам буккально / интраназально / в/м (0,1–0,2 мг/кг) или диазепам ректально 0,5 мг/кг (макс 20 мг)"],
      fill=GRN_F, stroke=GRN_S, tsize=19, bsize=16)
c.footer("Схема аудита 2026-10 к § 9.5.4, § 12.1.5, § 12.1.6, § 14.5. Дозы сверять с локальным протоколом и инструкцией к препарату.")
c.save(sys.argv[1])
