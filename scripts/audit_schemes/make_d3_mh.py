# -*- coding: utf-8 -*-
import sys; sys.path.insert(0, __import__('os').path.dirname(__import__('os').path.abspath(__file__)))
from svglib import *

c = Canvas(1600, 900)
c.title("Злокачественная гипертермия: что появляется раньше, а что — позже",
        "частоты по регистру NAMHR 1987–2006 (Larach et al., 2010, n = 286); порядок признаков у конкретного пациента варьирует")

# timeline axis
ax_y = 410
c.line(70, ax_y, 1540, ax_y, MUTED, 5, arrow=True)
c.text(70, ax_y + 36, "минуты от экспозиции к триггеру", 16, MUTED)
c.text(1500, ax_y + 36, "часы", 16, MUTED, "end")

phases = [
    (70, 500, "РАННИЕ (диагноз ставят здесь)", RED_F, RED_S,
     [("↑ EtCO₂ при неизменной вентиляции", "самый частый признак (> 90 % за время криза) и самый частый ПЕРВЫЙ признак"),
      ("Необъяснимая тахикардия", "≈ 70 % случаев; нередко одновременно с ростом EtCO₂"),
      ("Тризм (спазм жевательных мышц)", "после сукцинилхолина; изолированный тризм — повод для усиленного мониторинга")]),
    (590, 500, "РАЗВЁРНУТЫЙ КРИЗ", AMB_F, AMB_S,
     [("Генерализованная ригидность", "«пациент как доска», несмотря на миорелаксанты"),
      ("Смешанный ацидоз, гиперкалиемия", "pH < 7,25, BE < −8; K⁺ > 6 ммоль/л → аритмии"),
      ("Быстрый подъём температуры", "≈ 65 % случаев; может расти ~1 °C каждые 5–10 мин — но это ПОЗДНИЙ признак")]),
    (1110, 430, "ПОЗДНИЕ / ОСЛОЖНЕНИЯ", VIO_F, VIO_S,
     [("Миоглобинурия, ↑ КФК", "пик КФК через 12–24 ч; тёмная моча"),
      ("ДВС-синдром, ОПП, отёк мозга", "признаки фульминантного течения"),
      ("Рецидив (≈ 20 % случаев)", "наблюдение в ОРИТ ≥ 24 ч")]),
]
for x, w, t, f, s, items in phases:
    c.rect(x, 110, w, 260, f, s, 3, 16)
    c.text(x + 16, 146, t, 21, s, "start", True)
    yy = 180
    for h, d in items:
        yy = c.lines(x + 16, yy, wrap(h, w - 32, 18, True), 18, INK, "start", True) + 2
        yy = c.lines(x + 16, yy, wrap(d, w - 32, 15), 15, MUTED) + 10
    c.line(x + w / 2, 370, x + w / 2, ax_y - 6, s, 3)
    c.circle(x + w / 2, ax_y, 9, f, s, 3)

# action boxes
c.box(70, 470, 720, 330, "Действия в первые 10 минут (§ 9.6.1)",
      ["1. СТОП триггер: отключить ингаляционный анестетик, 100 % O₂ с потоком > 10 л/мин, угольные фильтры на оба колена контура, безтриггерная анестезия",
       "2. Позвать помощь (5–6 человек), взять дантролен",
       "3. Дантролен 2,5 мг/кг в/в быстро; повторять до ответа (снижение EtCO₂, ригидности, ЧСС); суммарно может потребоваться > 10 мг/кг",
       "4. Гипервентиляция, охлаждение, коррекция K⁺ и ацидоза, защита почек, мониторинг"],
      fill=GRN_F, stroke=GRN_S, tsize=21, bsize=16)
c.box(820, 470, 720, 330, "Типичные ошибки",
      ["• Ждать подъёма температуры, чтобы «подтвердить» диагноз",
       "• Списывать рост EtCO₂ на «гиповентиляцию» и просто увеличить минутный объём, не проверив остальное",
       "• Тратить время на замену наркозного аппарата вместо фильтров и высокого потока",
       "• Вводить блокаторы кальциевых каналов (верапамил, дилтиазем) на фоне дантролена — тяжёлая гиперкалиемия и остановка кровообращения (MHAUS)",
       "• Прекратить наблюдение раньше 24 ч — риск рецидива"],
      fill=RED_F, stroke=RED_S, tsize=21, bsize=16)

c.footer("Схема аудита 2026-10 к § 4.2.1, § 5.4.2, § 7.8.3, § 9.7.3. Шкала CGS (Larach, 1994): ≥ 50 баллов — «MH почти несомненна»; в остром периоде диагноз клинический, баллов не ждут.")
c.save(sys.argv[1])
