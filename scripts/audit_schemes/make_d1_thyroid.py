# -*- coding: utf-8 -*-
import sys; sys.path.insert(0, __import__('os').path.dirname(__import__('os').path.abspath(__file__)))
from svglib import *

c = Canvas(1600, 900)
c.title("Тиреотоксический криз: «блокада 4 в 1» — порядок и «кризовые» дозы",
        "по рекомендациям ATA 2016; диагноз клинический — лечение начинают, не дожидаясь результатов ТТГ и свТ4/Т3")

# --- trigger / suspicion block
c.box(40, 110, 1520, 94, None,
      ["Подозрение: тиреотоксикоз в анамнезе (Грейвс, узловой зоб, отмена тиреостатика) + лихорадка, тахикардия > 130/мин (часто ФП), "
       "делирий/возбуждение, рвота/диарея/желтуха, сердечная недостаточность.  Формализация: BWPS ≥ 45 баллов (25–44 — «назревающий криз») "
       "или критерии JTA (TS1/TS2). Уровень гормонов НЕ отличает криз от неосложнённого тиреотоксикоза."],
      fill=AMB_F, stroke=AMB_S, bsize=17)

# --- four blocks
bw, bh, gap = 355, 300, 33
x0, y0 = 40, 230
blocks = [
    ("1. Блокада синтеза", "t = 0 — первый шаг",
     ["Пропилтиоурацил: 500–1000 мг нагрузочно, затем по 250 мг каждые 4 ч "
      "(предпочтителен в первые дни: дополнительно тормозит конверсию Т4 → Т3)",
      "или тиамазол 60–80 мг/сут дробно (каждые 4–6 ч)",
      "Нет глотания — через зонд или ректально"], RED_F, RED_S),
    ("2. Блокада секреции", "t ≥ +1 ч — строго ПОСЛЕ тиреостатика",
     ["Неорганический йод: раствор Люголя 8–10 капель каждые 6–8 ч или насыщенный р-р KI 5 капель каждые 6 ч",
      "Раньше тиреостатика — йод станет «топливом» для синтеза новых гормонов"], BLU_F, BLU_S),
    ("3. Блокада симптомов", "параллельно, с первых минут",
     ["Пропранолол 60–80 мг каждые 4–6 ч внутрь (в высоких дозах также снижает конверсию Т4 → Т3)",
      "В/в: пропранолол 0,5–1 мг медленно под ЭКГ, повторно; или эсмолол 250–500 мкг/кг, затем 50–100 мкг/кг/мин",
      "СН, бронхоспазм — осторожно, короткодействующий препарат"], GRN_F, GRN_S),
    ("4. Глюкокортикоид", "параллельно",
     ["Гидрокортизон 300 мг в/в, затем по 100 мг каждые 8 ч",
      "или дексаметазон 2 мг каждые 6 ч",
      "Цель: блокада конверсии Т4 → Т3 и профилактика относительной надпочечниковой недостаточности"], VIO_F, VIO_S),
]
for i, (t, when, body, f, s) in enumerate(blocks):
    x = x0 + i * (bw + gap)
    c.rect(x, y0, bw, bh, f, s, 3, 16)
    c.text(x + 16, y0 + 36, t, 22, s, "start", True)
    c.text(x + 16, y0 + 62, when, 16, MUTED, "start", False, True)
    yy = y0 + 92
    for b in body:
        ls = wrap(b, bw - 32, 16)
        yy = c.lines(x + 16, yy, ls, 16, INK) + 8
    if i < 3:
        c.line(x + bw + 4, y0 + bh / 2, x + bw + gap - 4, y0 + bh / 2, MUTED, 3, arrow=True)

# --- timeline
ty = 575
c.line(60, ty, 1540, ty, MUTED, 4, arrow=True)
for xx, lab in [(60, "0 мин"), (60 + 355 + 33 + 20, "≥ 60 мин: йод"), (1300, "часы: оценка ответа")]:
    c.line(xx, ty - 10, xx, ty + 10, MUTED, 3)
    c.text(xx, ty + 32, lab, 15, MUTED, "start")

# --- supportive + don'ts
c.box(40, 625, 760, 200, "Плюс — обязательная поддержка",
      ["• Активное охлаждение физическими методами и парацетамол; салицилаты НЕ применять (вытесняют Т4/Т3 из связи с белками)",
       "• Инфузия с глюкозой, электролиты, поиск и лечение триггера (инфекция, операция, ДКА, отмена тиреостатика)",
       "• Рефрактерное течение: холестирамин 4 г × 4 р/сут, плазмаферез; по стабилизации — вопрос о тиреоидэктомии"],
      fill=GRY_F, stroke=GRY_S, tsize=20, bsize=16)
c.box(830, 625, 730, 200, "Чего не делать",
      ["• Йод до тиреостатика или без него",
       "• Салицилаты «для снижения температуры»",
       "• Дозы планового гипертиреоза (ПТУ 100–150 мг × 3, тиамазол 20–30 мг/сут) — при кризе недостаточны",
       "• Ждать гормоны, чтобы начать лечение; трактовать высокий свТ4 как «критерий тяжести»"],
      fill=RED_F, stroke=RED_S, tsize=20, bsize=16)

c.footer("Летальность: без лечения исторически ≈ 100 %, при современной терапии ≈ 10 % (регистр Японии, 2012), в сериях 8–25 % (ATA 2016). "
         "Схема аудита 2026-10 к § 4.2.3, § 7.4.1, § 9.6.5; дозы сверять с локальным протоколом и инструкцией.")
c.save(sys.argv[1])
