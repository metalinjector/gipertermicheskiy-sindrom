# -*- coding: utf-8 -*-
import sys; sys.path.insert(0, __import__('os').path.dirname(__import__('os').path.abspath(__file__)))
from svglib import *

c = Canvas(1600, 900)
c.title("Карта аудита (октябрь 2026): что и где изменено",
        "правки внесены только в главы/*.md; polnyy-tekst.md и PDF не пересобирались; подробности — АУДИТ-2026-10.md")

E, O, T, S, N = "E", "O", "T", "S", "N"
COL = {E: (RED_F, RED_S), O: (AMB_F, AMB_S), T: (BLU_F, BLU_S), S: (GRY_F, GRY_S)}
chapters = [
    ("1", "Введение и определения", [(E, "§ 1.4.6 перенесён и переписан"), (E, "§ 1.4.4 «необратимо» снято"), (O, "§ 1.3.2 антипиретики и исход"), (T, "§ 1.1.4 IVCT vs CHCT")]),
    ("2", "Физиология", [(O, "две модели терморегуляции"), (T, "TRPM2, парабрахиальный путь")]),
    ("3", "Патофизиология", [(S, "выводы: порог → зона риска"), (T, "кишечная ось, HSIC")]),
    ("4", "Этиология", [(E, "летальность тиреотокс. криза"), (E, "диагноз криза клинический"), (T, "heat injury (ACSM 2023)"), (S, "годы ссылок = ИСТОЧНИКИ")]),
    ("5", "Клиническая картина", [(E, "порядок ранних признаков MH"), (E, "судороги при T > 40 °C"), (S, "«несовместимо с жизнью»")]),
    ("6", "Диагностика", [(S, "«ЛДГ всегда повышена»")]),
    ("7", "Дифдиагностика", [(E, "единицы свТ4/Т3 → клиника"), (E, "критерии НЗС"), (E, "шкала CGS"), (O, "младенцы < 3 мес: AAP 2021"), (O, "BWPS vs критерии JTA")]),
    ("8", "Осложнения", [(N, "без правок"), (O, "диурез 1–2 vs 3 мл/кг/ч — в отчёте")]),
    ("9", "Неотложная помощь", [(E, "дозы при тиреотокс. кризе"), (E, "БКК + дантролен — нельзя"), (O, "дозы 2-й линии (ESETT)"), (T, "TACO; норадреналин 1-я линия")]),
    ("10", "Профилактика", [(N, "без правок")]),
    ("11", "Прогноз и исходы", [(T, "отдалённый СС- и почечный риск")]),
    ("12", "Особые категории", [(E, "диазепам в таблице доз"), (E, "целевая T у беременных")]),
    ("13", "Исследования", [(N, "без правок"), (S, "ссылки 2025–26 не верифицированы")]),
    ("14", "Клинические случаи", [(E, "случай 5: диазепам только при приступе")]),
    ("15", "Контроль знаний", [(N, "без правок")]),
]
cols, cw, chh, gx, gy = 5, 292, 226, 15, 8
x0, y0 = 40, 112
for i, (num, title, items) in enumerate(chapters):
    r, k = divmod(i, cols)
    x = x0 + k * (cw + gx); y = y0 + r * (chh + gy)
    has_err = any(t == E for t, _ in items)
    c.rect(x, y, cw, chh, "#ffffff", RED_S if has_err else GRY_S, 3 if has_err else 2, 12)
    c.circle(x + 26, y + 26, 16, INK, INK)
    c.text(x + 26, y + 32, num, 16, "#ffffff", "middle", True)
    c.lines(x + 50, y + 31, wrap(title, cw - 62, 15, True)[:1], 15, INK, "start", True)
    yy = y + 58
    for t, label in items:
        if t == N:
            c.text(x + 14, yy + 14, "— " + label, 14, MUTED, "start", False, True)
            yy += 26; continue
        f, s = COL[t]
        ls = wrap(label, cw - 60, 13)
        h = 12 + len(ls) * 17
        c.rect(x + 12, yy, cw - 24, h, f, s, 1.5, 8)
        c.lines(x + 24, yy + 15, ls, 13, INK)
        yy += h + 4

# legend
ly = 812
lx = 40
for t, label in [(E, "исправлена ошибка (уверенность 100 %)"), (O, "отмечены разные устоявшиеся мнения"), (T, "добавлена современная тенденция"), (S, "стиль / формулировка / согласованность")]:
    f, s = COL[t]
    c.rect(lx, ly, 26, 18, f, s, 1.5, 5)
    c.text(lx + 34, ly + 14, label, 14, INK)
    lx += 34 + text_width(label, 14) + 30
c.footer("Все схемы аудита: assets/audit/*.svg (источник) и *.png (экспорт resvg, 2400 × 1350).")
c.save(sys.argv[1])
