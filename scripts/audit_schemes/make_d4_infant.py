# -*- coding: utf-8 -*-
import sys; sys.path.insert(0, __import__('os').path.dirname(__import__('os').path.abspath(__file__)))
from svglib import *

c = Canvas(1600, 900)
c.title("Лихорадка ≥ 38 °C у младенца до 3 месяцев: два устоявшихся подхода",
        "слева — традиционное правило; справа — возраст-стратифицированная тактика (AAP 2021, NICE NG143); внизу — общее для всех")

# start box
c.box(500, 105, 600, 60, None, ["Ректальная T ≥ 38,0 °C у ребёнка младше 90 дней"], fill=GRY_F, stroke=GRY_S, bsize=19, align="center", vcenter=True)
c.line(800, 165, 800, 190, MUTED, 3, arrow=True)
# decision diamond
c.diamond(800, 255, 780, 130, AMB_F, AMB_S)
c.lines(800, 248, ["Плохо выглядит? Недоношенный? Младше 8 дней?", "Сопутствующая патология, антибиотики накануне, очаг инфекции?"], 15, INK, "middle", False, 1.3)
# yes branch
c.line(1190, 255, 1240, 255, RED_S, 3, arrow=True, red=True)
c.text(1200, 245, "да", 16, RED_S, "start", True)
c.box(1240, 190, 320, 130, "Полный объём — всегда", ["ОАК, посев крови, ОАМ + посев мочи, ЛП, эмпирические антибиотики в/в, госпитализация"],
      fill=RED_F, stroke=RED_S, tsize=17, bsize=15)
# no branch down
c.line(800, 320, 800, 338, MUTED, 3, arrow=True)
c.text(812, 333, "нет — хорошо выглядящий доношенный ребёнок", 15, MUTED)

# left: traditional
c.box(40, 340, 440, 300, "Традиционный подход (отечественная практика)",
      ["Всем до 3 месяцев: полный септический скрининг (ОАК, ОАМ и посев мочи, посев крови, ЛП), госпитализация, эмпирические антибиотики до результатов посевов.",
       "Плюсы: максимальная безопасность, не зависит от доступности ПКТ и наблюдения.",
       "Минусы: избыточные ЛП и антибиотики у части детей 1–3 мес с вирусной инфекцией."],
      fill=BLU_F, stroke=BLU_S, tsize=19, bsize=15)

# right: stratified columns
cols = [
    ("8–21 день", RED_F, RED_S, ["ОАМ, посев крови, ЛП, маркёры воспаления", "Антибиотики в/в", "Госпитализация", "(фактически = традиционный подход)"]),
    ("22–28 дней", AMB_F, AMB_S, ["ОАМ, посев крови, маркёры (ПКТ, АЧН, СРБ, T > 38,5)", "ЛП — выполнить или отложить по маркёрам", "Антибиотики — обычно; госпитализация в большинстве случаев"]),
    ("29–60 (90) дней", GRN_F, GRN_S, ["ОАМ, посев крови, маркёры воспаления", "Маркёры и ОАМ в норме → ЛП и антибиотики не рутинно, наблюдение 24–36 ч (возможно дома при надёжных родителях)", "Отклонения → ЛП, антибиотики, госпитализация"]),
]
x = 520
for t, f, s, items in cols:
    c.rect(x, 340, 335, 300, f, s, 3, 14)
    c.text(x + 14, 372, t, 20, s, "start", True)
    yy = 400
    for it in items:
        yy = c.lines(x + 14, yy, wrap("• " + it, 307, 15), 15, INK) + 6
    x += 350

# common box
c.box(40, 665, 1520, 150, "Обязательно при любом подходе",
      ["• Анализ и посев мочи (ИМВП — самая частая бактериальная инфекция этого возраста) • посев крови • прокальцитонин (лучший одиночный маркёр), АЧН, СРБ "
       "• повторный осмотр: состояние может измениться за часы • при герпетическом подозрении — ацикловир",
       "• Перегрев (укутывание, жаркое помещение, закрытый автомобиль) — диагноз исключения: температура нормализуется за 15–30 мин после устранения причины; при сомнениях действует правило инфекции."],
      fill=GRY_F, stroke=GRY_S, tsize=19, bsize=15)
c.footer("Схема аудита 2026-10 к § 7.7. Источники: Pantell RH et al., AAP Clinical Practice Guideline, Pediatrics 2021; NICE NG143 (2019+). Локальный протокол имеет приоритет.")
c.save(sys.argv[1])
